"""Compile a Python 3.13 universal lock using uv (only needed to update dependencies)."""

import hashlib
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "backend/requirements.txt"
LOCK = ROOT / "backend/requirements.lock"


def main():
    subprocess.run([sys.executable, "-m", "uv", "pip", "compile", str(SOURCE),
                    "--universal", "--python-version", "3.13", "--no-header", "--no-annotate",
                    "--output-file", str(LOCK), *sys.argv[1:]], check=True)
    digest = hashlib.sha256(SOURCE.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    LOCK.write_text("# Generated by python scripts/lock_backend.py; do not edit by hand.\n"
                    + "# requirements.txt sha256: " + digest + "\n"
                    + LOCK.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
