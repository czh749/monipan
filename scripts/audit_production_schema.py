"""Read-only production schema precheck; deploy the built single-file artifact."""

import json
import os
from pathlib import Path
import re
import subprocess


EMBEDDED_AUDIT = None
EXPECTED_SCHEMA = None
PREFIX = "MONIPAN_SCHEMA_AUDIT_RESULT="


def command(args, **kwargs):
    result = subprocess.run(args, capture_output=True, text=True, timeout=120, **kwargs)
    if result.returncode != 0:
        raise RuntimeError("Command failed: " + args[0] + " " + args[1] + "; raw output withheld")
    return result.stdout.strip()


def audit_host(source, expected):
    environment = dict(os.environ, COMPOSE_PROJECT_NAME="monipan")
    backend = command(["docker", "compose", "--project-directory", "/opt/monipan", "ps", "-q", "backend"],
                      env=environment)
    if not re.fullmatch(r"[0-9a-f]{64}", backend):
        raise RuntimeError("Expected one existing production backend container")
    template = '{"id":{{json .Id}},"running":{{json .State.Running}},"labels":{{json .Config.Labels}}}'
    container = json.loads(command(["docker", "inspect", "--format", template, backend]))
    labels = container.get("labels") or {}
    if not (container["id"] == backend and container["running"]
            and labels.get("com.docker.compose.project") == "monipan"
            and labels.get("com.docker.compose.service") == "backend"):
        raise RuntimeError("Production backend identity did not match")
    payload = source + '\nEXPECTED=' + repr(expected) + '''
import json
from sqlalchemy import event
from app.database import engine
try:
    if engine.dialect.name != "mysql":
        raise RuntimeError("Expected the production MySQL engine")
    event.listen(engine, "before_cursor_execute", reject_writes)
    with engine.connect() as connection:
        connection.exec_driver_sql("SET SESSION TRANSACTION READ ONLY")
        connection.commit()
        report = audit(connection, EXPECTED)
    print("MONIPAN_SCHEMA_AUDIT_RESULT=" + json.dumps(report, ensure_ascii=True))
except Exception as exc:
    print("MONIPAN_SCHEMA_AUDIT_RESULT=" + json.dumps({"status":"error", "error_type":type(exc).__name__}))
    raise SystemExit(1)
'''
    result = subprocess.run(["docker", "exec", "-i", backend, "python", "-B", "-"], input=payload,
                            capture_output=True, text=True, timeout=120)
    matches = [line[len(PREFIX):] for line in result.stdout.splitlines() if line.startswith(PREFIX)]
    if len(matches) != 1:
        raise RuntimeError("Schema audit did not return exactly one report")
    report = json.loads(matches[0])
    if result.returncode != 0 or report.get("status") not in {"matches_model_precheck", "differences_found"}:
        error_type = report.get("error_type", "unknown")
        if not isinstance(error_type, str) or not re.fullmatch(r"[A-Za-z]{1,64}", error_type):
            error_type = "unknown"
        raise RuntimeError("Schema audit did not complete: " + error_type)
    print(json.dumps(report, ensure_ascii=False, indent=2))
    print("SCHEMA_AUDIT_OK_READ_ONLY")


def main():
    if os.name != "posix" or not Path("/opt/monipan").is_dir():
        raise RuntimeError("Run on the existing Linux production host")
    if EMBEDDED_AUDIT is None or EXPECTED_SCHEMA is None:
        raise RuntimeError("Use the single-file artifact generated by build_schema_audit.py")
    audit_host(EMBEDDED_AUDIT, EXPECTED_SCHEMA)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("SCHEMA_AUDIT_FAILED " + type(exc).__name__ + ": " + str(exc))
        raise SystemExit(1)
