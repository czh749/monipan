"""Run backup -> isolated restore -> baseline rehearsal -> application checks.

The generated artifact bundles Python dependencies and candidate application
files. Only the disposable backend receives them. Production is not deployed.
"""

import base64
import io
import os
from pathlib import Path
import tempfile
import zipfile

from restore_mysql_drill import command, restore, require
from check_restore_application import check


BUNDLE = None


def bootstrap(bundle):
    return '''
import base64, io, json, os, shutil, sys, tempfile, zipfile
from pathlib import Path
try:
    root = Path(tempfile.mkdtemp(prefix="monipan-schema-candidate-"))
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(''' + repr(bundle) + '''))) as archive:
        require_names = {"scripts/migration_baseline_probe.py", "scripts/restore_application_probe.py"}
        if not require_names.issubset(set(archive.namelist())):
            raise RuntimeError("Incomplete candidate bundle")
        for item in archive.infolist():
            parts = Path(item.filename).parts
            if Path(item.filename).is_absolute() or ".." in parts or item.file_size > 8*1024*1024:
                raise RuntimeError("Unsafe candidate bundle entry")
        archive.extractall(root)
    application = root / "candidate/app"
    shutil.copytree("/app/app", application, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    for source in (root / "overlay/app").rglob("*"):
        if source.is_file():
            target = application / source.relative_to(root / "overlay/app")
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
    sys.path[:0] = [str(root / "candidate"), str(root / "vendor"), str(root / "scripts")]
    from migration_baseline_probe import run_migration_probe
    report = run_migration_probe()
    print("RESTORE_APPLICATION_RESULT=" + json.dumps(report, ensure_ascii=True))
    if report.get("status") != "passed":
        raise SystemExit(1)
except Exception as exc:
    print("RESTORE_APPLICATION_RESULT=" + json.dumps({"status":"failed", "error_type":type(exc).__name__}))
    raise SystemExit(1)
'''


def main():
    require(os.name == "posix", "Run on the existing Linux production host")
    require(BUNDLE is not None, "Use the artifact generated by build_schema_rehearsal.py")
    project = Path("/opt/monipan")
    require(project.is_dir() and (project / "scripts/backup_mysql.sh").is_file(), "Existing project is missing")
    os.umask(0o077)
    (project / "backups").mkdir(exist_ok=True)
    backup_dir = Path(tempfile.mkdtemp(prefix="migration-drill-20261018-", dir=project / "backups"))
    environment = dict(os.environ, COMPOSE_PROJECT_NAME="monipan", MONIPAN_BACKUP_DIR=str(backup_dir))
    print("MIGRATION_DRILL_BACKUP_DIR=" + str(backup_dir), flush=True)
    print(command(["/bin/sh", "scripts/backup_mysql.sh"], cwd=project, env=environment, timeout=600), flush=True)
    backups = list(backup_dir.glob("monipan-*.sql.gz"))
    require(len(backups) == 1, "Expected one new rehearsal backup")
    state = restore(backups[0], project)
    check(state, project, bootstrap(BUNDLE))
    print("BASELINE_REHEARSAL_OK_PRODUCTION_NOT_DEPLOYED")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("BASELINE_REHEARSAL_FAILED " + type(exc).__name__ + ": " + str(exc))
        raise SystemExit(1)
